#include "CalorimeterHit.hh"
#include "G4ios.hh"
#include "G4SystemOfUnits.hh"

//----------------------------------------------------------------------//
// Declaration of the allocator                                         //
//----------------------------------------------------------------------//
G4Allocator<CalorimeterHit> CalorimeterHitAllocator;
//----------------------------------------------------------------------//
//----------------------------------------------------------------------//


//----------------------------------------------------------------------//
// Constructor                                                          //
//----------------------------------------------------------------------//
CalorimeterHit::CalorimeterHit(G4int layer, G4bool isScintillator) {
    layerID = layer;
    scintillator = isScintillator;
    energy = 0.0;
}
//----------------------------------------------------------------------//
//----------------------------------------------------------------------//


//----------------------------------------------------------------------//
// Destructor                                                           //
//----------------------------------------------------------------------//
CalorimeterHit::~CalorimeterHit() {
    ;
}
//----------------------------------------------------------------------//
//----------------------------------------------------------------------//


//----------------------------------------------------------------------//
// Accumulate the energy of a step                                      //
//----------------------------------------------------------------------//
void CalorimeterHit::AddStep(G4double edep, G4ThreeVector pos) {
    energy += edep;
    weightedPos += edep * pos;
}
//----------------------------------------------------------------------//
//----------------------------------------------------------------------//


//----------------------------------------------------------------------//
// Print                                                                //
//----------------------------------------------------------------------//
void CalorimeterHit::Print() {
    G4cout << "\033[1;34m" << "Layer: " << layerID << (scintillator ? " scintillator" : " absorber")
           << ", energy: " << energy/MeV << " MeV" << "\033[0m" << G4endl;
}
